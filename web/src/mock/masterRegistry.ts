/**
 * Built to the universal master design standard.
 *
 * These masters differ only in their fields and their rules, so they are
 * declared as data and rendered by one screen. Adding "Surface Coating" as a
 * master is an entry in this file, not a new page — which is the whole promise
 * of a master-data framework.
 */

let seq = 0
const row = (
  code: string,
  name: string,
  values: Record<string, string | number | boolean | null>,
  o: Partial<Pick<SimpleMasterRow, 'status' | 'usageCount' | 'revision' | 'effectiveTo'>> = {},
): SimpleMasterRow => {
  seq += 1
  const ageDays = 40 + ((seq * 37) % 900)
  return {
    uid: `smr-${String(seq).padStart(4, '0')}`,
    code,
    name,
    status: o.status ?? ('ACTIVE' as MasterStatus),
    effectiveFrom: daysAgo(ageDays),
    effectiveTo: o.effectiveTo ?? null,
    revision: o.revision ?? 1,
    usageCount: o.usageCount ?? (seq * 13) % 180,
    modifiedBy: ['Anand Krishnan', 'Rahul Iyer', 'Priya Menon', 'Deepa Shankar', 'Suresh Babu'][seq % 5],
    modifiedAt: daysAgo((seq * 11) % 120, 14),
    values,
  }
}

