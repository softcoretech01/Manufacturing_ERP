const doc = (
  uid: string,
  type: string,
  documentNo: string,
  issuedBy: string,
  validForDays: number,
): ComplianceDoc => {
  const status: ComplianceDoc['status'] =
    validForDays < 0 ? 'EXPIRED' : validForDays < 45 ? 'EXPIRING' : 'VALID'
  return {
    uid,
    type,
    documentNo,
    issuedBy,
    validFrom: daysAgo(400),
    validTo: validForDays < 0 ? daysAgo(-validForDays) : daysAhead(validForDays),
    status,
    fileName: `${type.toLowerCase().replace(/\W+/g, '-')}.pdf`,
  }
}

const rev = (
  revision: number,
  daysBack: number,
  by: string,
  reason: string,
  changes: RevisionEntry['changes'],
  approvedBy: string | null = 'Meera Rajan',
): RevisionEntry => ({
  revision,
  at: daysAgo(daysBack, 11),
  by,
  reason,
  changes,
  approvedBy,
})

const used = (
  module: string,
  documentType: string,
  documentNo: string,
  status: string,
  daysBack: number,
  isOpen: boolean,
): WhereUsedEntry => ({
  module,
  documentType,
  documentNo,
  status,
  date: daysAgo(daysBack),
  isOpen,
})

